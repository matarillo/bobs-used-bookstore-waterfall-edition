export function traceability() {
  const sources=[['機能要件','04-functional-requirements.md','FR'],['業務ルール','05-business-rules.md','RULE'],['主要エンティティ','07-data-requirements.md','ENT'],['非機能要件','09-non-functional-requirements.md','NFR']];
  let text=''; const covered=new Set();
  for(const [label,file,prefix] of sources) {
    const source=readFileSync(new URL('../../../requirements/'+file,import.meta.url),'utf8');
    const ids=[...new Set([...source.matchAll(new RegExp('^\\| `('+prefix+'-[A-Z0-9-]+)` \\|','gm'))].map(m=>m[1]))];
    assert.ok(ids.length);
    text+=`## ${label}（${ids.length}件）\n\n| 要件 | 対象モデル・契約 | DB検証ケース | 検証範囲 |\n| --- | --- | --- | --- |\n`;
    for(const id of ids) {
      covered.add(id); assert.ok(map[id],`Unmapped requirement: ${id}`); const r=map[id];
      text+=`| [${id}](../../requirements/${file}) | ${r.model} | ${r.tests} | ${r.scope} |\n`;
    }
    text+='\n';
  }
  assert.deepEqual([...covered].sort(),Object.keys(map).sort(),'Traceability metadata must exactly cover requirement rows');
  return text;
}
